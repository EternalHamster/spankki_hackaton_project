import { locale } from './language.js';
import { getLanguage } from './language.js';
import { translate } from './translations.js';
const euros = (value, digits = 0) => new Intl.NumberFormat(locale(), { style: 'currency', currency: 'EUR', maximumFractionDigits: digits }).format(value);
const cents = value => Math.round(value * 100);
const money = value => typeof value === 'number' && Number.isFinite(value) && value >= 0 &&
  value <= 1000000 && Math.abs(value * 100 - cents(value)) < 1e-6;
const date = value => typeof value === 'string' && /^\d{4}-\d{2}-\d{2}$/.test(value) &&
  Number.isFinite(Date.parse(value + 'T00:00:00Z')) && new Date(value + 'T00:00:00Z').toISOString().slice(0, 10) === value;

// A plan calculated from the recorded week, not text generated by a model or a bank balance.
export function weeklyPlan(week, selection, level = 'standard') {
  if (!['simple', 'standard', 'detailed'].includes(level)) throw new TypeError('Tuntematon vastausten taso.');
  if (!week || week.observed_through !== selection?.as_of ||
      ![week.week_start, week.week_end, week.observed_through].every(date) ||
      week.week_start > week.observed_through || week.observed_through > week.week_end ||
      new Date(week.week_start + 'T00:00:00Z').getUTCDay() !== 1 ||
      (Date.parse(week.week_end) - Date.parse(week.week_start)) / 86400000 !== 6 ||
      !['weekly_budget_eur', 'spent_eur_week', 'remaining_eur_week', 'over_budget_eur_week'].every(key => money(week[key])) ||
      !Number.isInteger(week.days_remaining_in_week) || week.days_remaining_in_week < 0 || week.days_remaining_in_week > 6 ||
      week.days_remaining_in_week !== (Date.parse(week.week_end) - Date.parse(week.observed_through)) / 86400000 ||
      cents(week.remaining_eur_week) !== Math.max(0, cents(week.weekly_budget_eur) - cents(week.spent_eur_week)) ||
      cents(week.over_budget_eur_week) !== Math.max(0, cents(week.spent_eur_week) - cents(week.weekly_budget_eur)) ||
      (week.days_remaining_in_week > 0 ? !money(week.daily_remaining_eur) ||
        cents(week.daily_remaining_eur) !== Math.floor(cents(week.remaining_eur_week) / week.days_remaining_in_week) : week.daily_remaining_eur !== null)) {
    throw new TypeError('Viikkosuunnitelman tiedot eivät kelpaa.');
  }
  const days = week.days_remaining_in_week;
  let bullets;
  if (week.weekly_budget_eur === 0) {
    bullets = ['Arviossa ei ole varaa uusiin lisäostoihin. Siirrä vapaaehtoinen hankinta myöhemmäksi.',
      'Varaa rahat ensin laskuihin, ruokaan ja muihin välttämättömiin menoihin.'];
  } else if (week.over_budget_eur_week > 0) {
    bullets = [`Viikkoraja ylittyi ${euros(week.over_budget_eur_week)}. Siirrä uudet lisäostokset ensi viikkoon, jotta ylitys ei kasva.`,
      'Pidä laskuihin ja muihin välttämättömiin menoihin varatut rahat erillään lisäostoista.'];
  } else if (week.remaining_eur_week === 0) {
    bullets = ['Viikon lisäostoraja on käytetty. Siirrä seuraava vapaaehtoinen ostos ensi viikkoon.',
      'Pidä laskuihin ja muihin välttämättömiin menoihin varatut rahat erillään lisäostoista.'];
  } else if (days > 0) {
    bullets = [`Jaa jäljellä oleva ${euros(week.remaining_eur_week)} ${days === 1 ? 'viimeiselle päivälle' : `${days} päivälle`}: noin ${euros(week.daily_remaining_eur)} päivässä.`,
      'Jos käytät yhtenä päivänä enemmän, vähennä sama summa muiden päivien lisäostoista.'];
    if (days === 1) bullets[1] = 'Jos ostos ylittää jäljellä olevan rajan, siirrä se ensi viikkoon tai arvioi sitä valmentajan kanssa.';
  } else {
    bullets = [`Viikko on päättynyt. Suunnittelurajasta jäi ${euros(week.remaining_eur_week)} käyttämättä; summa ei ole tilisi saldo.`,
      'Tee seuraavalle viikolle uusi lisäostosuunnitelma uusimpien tulojen ja laskujen perusteella.'];
  }
  if (level === 'simple') {
    if (week.weekly_budget_eur === 0) {
      bullets = ['Siirrä ylimääräiset ostokset myöhemmäksi. Arviossa niihin ei jää rahaa.',
        'Varaa rahat ensin laskuihin, ruokaan ja muihin pakollisiin menoihin.'];
    } else if (week.over_budget_eur_week > 0) {
      bullets = [`Lisäostoihin meni ${euros(week.over_budget_eur_week)} yli viikon arvion. Odota seuraavien lisäostosten kanssa ensi viikkoon.`,
        'Pidä laskuihin ja muihin pakollisiin menoihin varatut rahat erillään.'];
    } else if (week.remaining_eur_week === 0) {
      bullets = ['Viikon lisäostovara on käytetty. Odota seuraavien lisäostosten kanssa ensi viikkoon.',
        'Pidä laskuihin ja muihin pakollisiin menoihin varatut rahat erillään.'];
    } else if (days > 0) {
      bullets = [`Varaa loppuviikon lisäostoihin noin ${euros(week.daily_remaining_eur)} päivässä.`,
        days > 1 ? 'Jos käytät tänään enemmän, käytä muina päivinä vähemmän.' : 'Siirrä tätä suurempi ostos ensi viikkoon.'];
    } else {
      bullets = [`Viikon arviosta jäi ${euros(week.remaining_eur_week)} käyttämättä. Se ei tarkoita tilisi saldoa.`,
        'Suunnittele seuraavan viikon lisäostot tulojen ja laskujen mukaan.'];
    }
  } else if (level === 'detailed') {
    bullets.push(`Arvioitu viikkoraja on ${euros(week.weekly_budget_eur)} ja kirjatut lisäostot ${euros(week.spent_eur_week)}. ` +
      (week.over_budget_eur_week > 0 ? `Erotus on ${euros(week.over_budget_eur_week)} yli rajan. ` : `Erotuksesta jää ${euros(week.remaining_eur_week)}. `) +
      (days > 0 ? `Päiväraja saadaan jakamalla jäljellä oleva määrä ${days} päivälle ja pyöristämällä alaspäin sentteihin. ` : '') +
      'Tämä on suunnitteluraja, ei tilin saldo.');
  }
  const language = getLanguage();
  if (language === 'en') bullets = bullets.map(text => translate(text, language));
  const question = language === 'en' ? `How can I stay within my optional spending plan? Week ${week.week_start}–${week.week_end}, recorded through ${week.observed_through}. Estimated weekly limit ${euros(week.weekly_budget_eur, 2)}, recorded spending ${euros(week.spent_eur_week, 2)}, remaining allowance ${euros(week.remaining_eur_week, 2)}. This difference is not an account balance or a fresh safe-to-spend estimate.`
    : `Miten pysyn lisäostojen suunnittelurajassa? Aineiston viikko ${week.week_start}–${week.week_end}, tiedot ${week.observed_through} asti. ` +
    `Viikkoraja on arvio ${euros(week.weekly_budget_eur, 2)}, kirjattu kulutus ${euros(week.spent_eur_week, 2)} ja rajasta jäljellä ${euros(week.remaining_eur_week, 2)}. ` +
    'Rajan ja kulutuksen erotus ei ole tilin saldo eikä uusi turvallisen käyttövaran arvio.';
  const displayQuestion = language === 'en'
    ? `How should I use the rest of my weekly allowance?${level === 'simple' ? '' : ` Data through ${week.observed_through}.`}`
    : `Miten käytän loppuviikon lisäostovaran?${level === 'simple' ? '' : ` Tiedot ${week.observed_through} asti.`}`;
  return { bullets, question, language, displayQuestion,
    answer: bullets.map(text => `• ${text}`).join('\n'), selectionId: selection.selection_id, source: 'calculated', level };
}
