export function translate(text, language = 'fi') {
  if (language !== 'en' || typeof text !== 'string') return text;
  const trimmed = text.trim().replace(/\s+/g, ' ');
  if (ENGLISH_COPY.has(trimmed)) return text.replace(text.trim(), ENGLISH_COPY.get(trimmed));
  for (const [pattern, replacement] of ENGLISH_PATTERNS) {
    if (pattern.test(trimmed)) return text.replace(text.trim(), trimmed.replace(pattern, replacement).replace(phrasePattern, source => ENGLISH_COPY.get(source)));
  }
  return text.replace(phrasePattern, source => ENGLISH_COPY.get(source));
}
